# This script asks the user for their name and how many pizzas they want to order.
# It checks if the order qualifies as a large party order and prints a custom message.

# 1. Two variables from user input using input() twice
name = input("Please enter your name: ")
pizza_str = input("How many pizzas would you like to order? ")

# Convert the input string into a number (integer)
pizza_count = int(pizza_str)

# 2. A conditional (if/else) that tests one of the entered values
# 3. Uses a number directly in the code (5)
if pizza_count > 5:
    # 4. A print statement that uses two of your variables (name and pizza_count)
    print(f"Wow {name}! Ordering {pizza_count} pizzas is a big order. It will take 45 minutes.")
else:
    print(f"Thanks {name}, your order of {pizza_count} pizzas will be ready in 20 minutes.")

